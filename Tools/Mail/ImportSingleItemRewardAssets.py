def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def identifier(path):
 meta=Path(str(path)+'.meta')
 return re.search(r'^guid: (\w+)',meta.read_text(encoding='utf-8'),re.M)[1] if meta.exists() else uuid.uuid5(uuid.NAMESPACE_URL,'AstralOath/'+path.relative_to(ROOT).as_posix()).hex
def move_with_guid(source,destination):
 for old,new in [(source,destination),(Path(str(source)+'.meta'),Path(str(destination)+'.meta'))]:
  if old.exists():
   if new.exists():raise FileExistsError('Refuse ambiguous duplicate during GUID-preserving move: '+str(new))
   new.parent.mkdir(parents=True,exist_ok=True);old.rename(new)
def sprite_meta(path,srgb=False):
 meta=Path(str(path)+'.meta')
 text=meta.read_text(encoding='utf-8') if meta.exists() else (COMMON/'Textures/cm_item_slot.png.meta').read_text(encoding='utf-8')
 text=re.sub(r'^guid: .*$', 'guid: '+identifier(path),text,flags=re.M)
 for key,value in [('enableMipMap',0),('sRGBTexture',int(srgb)),('spriteMode',1),('textureType',8),('spriteMeshType',0),('alphaIsTransparency',0)]:
  text=re.sub(r'\b'+key+r': \d+',key+': '+str(value),text)
 text=re.sub(r'^  spriteBorder: .*$', '  spriteBorder: {x: 0, y: 0, z: 0, w: 0}',text,flags=re.M)
 text=re.sub(r'^  userData:.*$', '  userData: AstralOath.ImportOverride',text,flags=re.M)
 text=re.sub(r'textureCompression: \d+','textureCompression: 0',text)
 text=re.sub(r'textureFormat: -1','textureFormat: 4',text)
 meta.write_text(text,encoding='utf-8',newline='\n')
def plain_meta(path,kind):
 meta=Path(str(path)+'.meta')
 if not meta.exists():meta.write_text('fileFormatVersion: 2\nguid: '+identifier(path)+'\n'+kind+':\n  externalObjects: {}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n',encoding='utf-8')

