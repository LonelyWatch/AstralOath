"""Import only the source dependency closure for the battle HUD effects."""

import argparse
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path, PurePosixPath
import sys

TOOLS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOLS / "CharacterAssets"))
from convert import decode_scsp, decode_sct
from import_characters import Closure, atlas_pages, hash_file, resolve_atlas, safe_source

MODULE = TOOLS.parent / "Assets/Game/Modules/BattleScene"
OUTPUT = MODULE / "Res/Effects/Hud"
RAW_DIRECTORY = "原始资源"
ROOTS = (
    "effect/soul_burn_bt.scsp",
    "effect/soul_01.cfx",
    "effect/hud_skill_select_nomal.cfx",
    "effect/hud_skill_select_burn.cfx",
    "effect/ui_soul_burn_use.cfx",
    "img/game_hud_btn_burnc_d.png",
    "img/game_hud_btn_burnc_p.png",
)


def json_bytes(document, *, compact=False):
    if compact:
        return json.dumps(document, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode("utf-8")
    return (json.dumps(document, ensure_ascii=False, indent=2, allow_nan=False) + "\n").encode("utf-8")


def asset_path(source):
    path = PurePosixPath(source)
    suffixes = {
        ".scsp": ".spine.json",
        ".atlas": ".atlas.txt",
        ".sct": ".png",
        ".sct2": ".png",
        ".cfx": ".cfx.json",
        ".particle": ".particle.json",
        ".png": ".png",
    }
    if path.suffix not in suffixes:
        raise ValueError(f"Unsupported battle HUD dependency: {source}")
    name = path.stem + suffixes[path.suffix]
    return "Particles/" + name if path.parent.name == "particle" or path.suffix == ".particle" else name


def collect(root):
    closure = Closure(root)
    for source in ROOTS:
        closure.include(source, "battle-hud")

    paths = {source: asset_path(source) for source in closure.dependencies}
    if len(set(paths.values())) != len(paths):
        raise ValueError("Duplicate battle HUD output paths")

    payloads = {}
    files = []
    for source, target in sorted(paths.items()):
        source_path = safe_source(root, source)
        entry = {
            "source": f"{RAW_DIRECTORY}/{source}",
            "sourceSha256": hash_file(source_path),
            "asset": target,
            "dependencies": [paths[dependency] for dependency in closure.dependencies[source]],
        }
        suffix = source_path.suffix
        if suffix == ".scsp":
            skeleton, report = decode_scsp(source_path.read_bytes())
            atlas = str(PurePosixPath(source).with_suffix(".atlas"))
            entry["spineVersion"] = report["spineVersion"]
            entry["animations"] = report["animations"]
            entry["pages"] = [
                {"pageName": page["name"], "asset": paths[page["source"]]}
                for page in atlas_pages(root, atlas)
            ]
            content = json_bytes(skeleton, compact=True)
        elif suffix == ".png":
            content = source_path.read_bytes()
        elif suffix == ".atlas":
            atlas = resolve_atlas(root, source)
            content = safe_source(root, atlas).read_bytes()
        elif suffix in (".sct", ".sct2"):
            image, texture = decode_sct(source_path.read_bytes())
            encoded = BytesIO()
            image.save(encoded, format="PNG")
            content = encoded.getvalue()
            entry["texture"] = texture
        else:
            content = json_bytes(closure.structures[source])

        entry["assetSha256"] = sha256(content).hexdigest()
        payloads[target] = content
        files.append(entry)

    payloads["source.json"] = json_bytes({
        "schemaVersion": 1,
        "converterSha256": hash_file(TOOLS / "CharacterAssets/convert.py"),
        "roots": list(ROOTS),
        "files": files,
    })
    return payloads


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(r"D:\sevenepic"))
    parser.add_argument("--check", action="store_true", help="Check generated bytes without writing assets.")
    args = parser.parse_args()

    source = (args.source / RAW_DIRECTORY).resolve(strict=True)
    if OUTPUT.resolve().is_relative_to(source):
        raise ValueError("Battle HUD assets cannot be written to the source directory.")
    payloads = collect(source)
    mismatches = []
    for relative, content in payloads.items():
        target = OUTPUT / relative
        if target.is_file() and target.read_bytes() == content:
            continue
        if args.check:
            mismatches.append(relative)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
    if mismatches:
        parser.exit(1, "Missing or changed battle HUD assets:\n" + "\n".join(mismatches) + "\n")
    action = "Verified" if args.check else "Imported"
    print(f"{action} {len(payloads) - 1} battle HUD assets and their source manifest.")


if __name__ == "__main__":
    main()
