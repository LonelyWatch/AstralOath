"""Verify or restore the exact HUD and forest textures listed in their source manifests."""
import argparse
import hashlib
import io
import json
import sys
from functools import lru_cache
from pathlib import Path

import numpy as np
from PIL import Image

REPO = Path(__file__).resolve().parents[2]
TEXTURES = REPO / "Assets/Game/Modules/BattleScene/Res/Textures"
sys.path.insert(0, str(REPO / "Tools/CharacterAssets"))
from convert import decode_sct


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def read_manifest(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def within(root, relative):
    path = (root / relative).resolve()
    if not path.is_relative_to(root):
        raise ValueError(f"Path outside {root}: {relative}")
    return path


@lru_cache(maxsize=None)
def verified_read(root, relative, expected):
    data = within(root, relative).read_bytes()
    if sha256(data) != expected:
        raise ValueError(f"Source hash changed: {relative}")
    return data


def write_or_verify(path, data, expected, restore):
    if sha256(data) != expected:
        raise ValueError(f"Generated bytes differ from manifest: {path.name}")
    if restore:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    elif path.read_bytes() != data:
        raise ValueError(f"Imported bytes differ from manifest: {path.name}")


@lru_cache(maxsize=2)
def load_atlas(source, relative, expected):
    image, _ = decode_sct(verified_read(source, relative, expected))
    return image


def restore_background(source, entry, restore):
    verified_read(source, entry["atlasSource"], entry["atlasSha256"])
    atlas = load_atlas(source, entry["source"], entry["sourceSha256"])
    x, y = entry["cropTopLeft"]
    width, height = entry["cropSize"]
    pixels = np.asarray(atlas.crop((x, y, x + width, y + height)), dtype=np.uint8)
    if sha256(pixels.tobytes()) != entry["sourceCropRgbaSha256"]:
        raise ValueError(f"Atlas region changed: {entry['region']}")

    alpha = pixels[:, :, 3:4].astype(np.uint32)
    rgb = pixels[:, :, :3].astype(np.uint32)
    straight = pixels.copy()
    straight[:, :, :3] = np.minimum(255, (rgb * 255 + alpha // 2) // np.maximum(1, alpha))
    straight[alpha[:, :, 0] == 0, :3] = 0
    if sha256(straight.tobytes()) != entry["outputRgbaSha256"]:
        raise ValueError(f"Straight alpha conversion changed: {entry['region']}")
    output = io.BytesIO()
    Image.fromarray(straight, "RGBA").save(output, format="PNG")
    relative = Path(entry["path"]).relative_to(TEXTURES.relative_to(REPO))
    write_or_verify(within(TEXTURES, relative), output.getvalue(), entry["outputSha256"], restore)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default=Path(r"D:\sevenepic"), type=Path)
    parser.add_argument("--restore", action="store_true", help="Reproduce textures instead of comparing existing files")
    args = parser.parse_args()
    source = args.source.resolve(strict=True)

    hud = read_manifest(TEXTURES / "Hud/source-manifest.json")["assets"]
    for asset in hud:
        data = verified_read(source, asset["source"], asset["sha256"])
        write_or_verify(within(TEXTURES / "Hud", asset["asset"]), data, asset["sha256"], args.restore)

    backgrounds = read_manifest(TEXTURES / "Backgrounds/background-import-manifest.json")["entries"]
    for entry in backgrounds:
        restore_background(source, entry, args.restore)

    cinematic = read_manifest(REPO / "Assets/Game/Modules/BattleScene/Res/Effects/Cinematic/source.json")["entries"]
    for entry in cinematic:
        relative = Path(entry["source"]).relative_to(Path("D:/sevenepic"))
        data = verified_read(source, relative, entry["sha256"])
        if "destination" in entry:
            write_or_verify(within(REPO, entry["destination"]), data, entry["sha256"], args.restore)

    verb = "Restored" if args.restore else "Verified"
    print(f"{verb} {len(hud)} HUD source files and {len(backgrounds)} forest layers; checked 3 cinematic textures and source shader provenance.")


if __name__ == "__main__":
    main()
